"""
Common data models used throughout THERMO-X.

This file defines the structures used to move sensor data,
actuator commands, and derived thermal information between
the simulator, controller, dashboard, analytics, and future
ESP32 hardware interface.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum


class SystemState(str, Enum):
    """Overall operating state of the THERMO-X system."""

    SAFE = "SAFE"
    WARNING = "WARNING"
    EMERGENCY = "EMERGENCY"
    FAULT = "FAULT"


class CoolingMode(str, Enum):
    """Cooling strategy currently being used."""

    ADAPTIVE = "ADAPTIVE"
    FIXED = "FIXED"
    SHUTDOWN = "SHUTDOWN"


@dataclass(slots=True)
class SensorSnapshot:
    """
    One complete measurement sample from a thermal module.

    IMPORTANT:
    This class is intentionally independent of hardware.

    A future ESP32 adapter will simply populate this same structure
    using real sensor measurements.
    """

    # Simulation/measurement time.
    timestamp_s: float

    # Identifies the thermal zone/server.
    server_id: str

    # Experimental workload level.
    # This is a normalized workload indicator, not necessarily
    # actual CPU/GPU utilization.
    workload_pct: float

    # Electrical heater power representing computational heat.
    # This is an experimental thermal-load input.
    heater_power_w: float

    # Temperature of the simulated/physical thermal source.
    temperature_c: float

    # Coolant temperature entering the cold plate/module.
    coolant_inlet_c: float

    # Coolant temperature leaving the module.
    coolant_outlet_c: float

    # Coolant flow through this branch.
    flow_rate_lpm: float

    # Loop pressure.
    pressure_kpa: float

    # Ambient air temperature.
    ambient_temperature_c: float

    # Safety sensor information.
    leak_detected: bool = False
    sensors_valid: bool = True

    @property
    def coolant_delta_t_c(self) -> float:
        """
        Temperature rise of coolant across the thermal module.

        Delta T = T_out - T_in
        """

        return self.coolant_outlet_c - self.coolant_inlet_c


@dataclass(slots=True)
class ActuatorCommand:
    """
    Command generated by the THERMO-X control system.

    Percentages use the range 0-100.

    The same structure can eventually be sent to:
        - simulated actuators
        - ESP32 firmware
    """

    # Shared cooling-loop pump.
    pump_speed_pct: float = 0.0

    # Shared radiator fan.
    fan_speed_pct: float = 0.0

    # Individual cooling branch valve positions.
    # Example:
    # {"SERVER_A": 40.0, "SERVER_B": 85.0}
    valve_positions_pct: dict[str, float] | None = None

    # Safety layer can disable the heater.
    heater_enabled: bool = True

    # Current operating mode.
    cooling_mode: CoolingMode = CoolingMode.ADAPTIVE

    # Overall safety state.
    system_state: SystemState = SystemState.SAFE

    # Human-readable explanation for the command.
    reason: str = ""

    def __post_init__(self) -> None:
        """Ensure the valve dictionary always exists."""

        if self.valve_positions_pct is None:
            self.valve_positions_pct = {}


@dataclass(slots=True)
class ThermalMetrics:
    """
    Derived thermal/control values.

    These values will later feed:
        - dashboard
        - CSV logging
        - experiments
        - ML features
    """

    heat_removed_w: float = 0.0
    coolant_delta_t_c: float = 0.0

    pump_power_w: float = 0.0
    fan_power_w: float = 0.0
    total_cooling_power_w: float = 0.0

    # 0 = very low thermal demand
    # 1 = very high thermal demand
    thermal_demand_index: float = 0.0