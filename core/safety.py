"""
Level-1 safety controller for THERMO-X.

Safety always has authority over adaptive/resource optimization.

Priority:

    SAFETY
       ↓
    RELIABILITY
       ↓
    RESOURCE OPTIMIZATION
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Sequence

from .models import (
    ActuatorCommand,
    CoolingMode,
    SensorSnapshot,
    SystemState,
)


@dataclass(slots=True)
class SafetyLimits:
    """
    Configurable software safety limits.

    IMPORTANT:
    These are ONLY initial simulator limits.

    They are NOT hardware ratings.

    Real prototype limits must be determined from the
    specifications/datasheets of the actual components.
    """

    # Normal operating upper temperature.
    max_safe_temperature_c: float = 70.0

    # Critical emergency temperature.
    critical_temperature_c: float = 80.0

    # Minimum acceptable coolant flow.
    min_flow_lpm: float = 0.20

    # Maximum allowed simulated loop pressure.
    max_pressure_kpa: float = 150.0


@dataclass(slots=True)
class SafetyDecision:
    """Decision generated by the safety controller."""

    state: SystemState

    # Force maximum cooling?
    force_max_cooling: bool

    # Disable the heat source?
    disable_heater: bool

    # Disable the pump?
    disable_pump: bool

    # Explanation for dashboard/logging.
    reason: str


class SafetyController:
    """
    Level-1 hard safety controller.

    This controller does not optimize anything.

    Its job is to detect unsafe conditions and override
    the normal adaptive controller when necessary.
    """

    def __init__(
        self,
        limits: SafetyLimits | None = None,
    ) -> None:

        self.limits = limits or SafetyLimits()

    def evaluate(
        self,
        snapshots: Sequence[SensorSnapshot],
    ) -> SafetyDecision:
        """
        Evaluate the latest sensor data.

        The first critical problem found becomes the safety decision.
        """

        # No sensor information means we cannot safely control the system.
        if not snapshots:
            return SafetyDecision(
                state=SystemState.FAULT,
                force_max_cooling=True,
                disable_heater=True,
                disable_pump=True,
                reason="No sensor data available.",
            )

        for snapshot in snapshots:

            # Sensor failure.
            if not snapshot.sensors_valid:
                return SafetyDecision(
                    state=SystemState.FAULT,
                    force_max_cooling=True,
                    disable_heater=True,
                    disable_pump=True,
                    reason=(
                        f"Invalid sensor data: "
                        f"{snapshot.server_id}."
                    ),
                )

            # Leak detection.
            if snapshot.leak_detected:
                return SafetyDecision(
                    state=SystemState.EMERGENCY,
                    force_max_cooling=False,
                    disable_heater=True,
                    disable_pump=True,
                    reason=(
                        f"Leak detected at "
                        f"{snapshot.server_id}."
                    ),
                )

            # Excessive pressure.
            if (
                snapshot.pressure_kpa
                > self.limits.max_pressure_kpa
            ):
                return SafetyDecision(
                    state=SystemState.EMERGENCY,
                    force_max_cooling=True,
                    disable_heater=True,
                    disable_pump=True,
                    reason=(
                        f"Pressure limit exceeded at "
                        f"{snapshot.server_id}."
                    ),
                )

            # Critical temperature.
            if (
                snapshot.temperature_c
                >= self.limits.critical_temperature_c
            ):
                return SafetyDecision(
                    state=SystemState.EMERGENCY,
                    force_max_cooling=True,
                    disable_heater=True,
                    disable_pump=False,
                    reason=(
                        f"Critical temperature at "
                        f"{snapshot.server_id}."
                    ),
                )

            # Loss of flow while heat is being generated.
            if (
                snapshot.flow_rate_lpm
                < self.limits.min_flow_lpm
                and snapshot.heater_power_w > 0
            ):
                return SafetyDecision(
                    state=SystemState.EMERGENCY,
                    force_max_cooling=True,
                    disable_heater=True,
                    disable_pump=False,
                    reason=(
                        f"Insufficient coolant flow at "
                        f"{snapshot.server_id}."
                    ),
                )

        # Warning state if we are above normal operating temperature
        # but haven't reached the critical limit.
        if any(
            snapshot.temperature_c
            >= self.limits.max_safe_temperature_c
            for snapshot in snapshots
        ):
            return SafetyDecision(
                state=SystemState.WARNING,
                force_max_cooling=True,
                disable_heater=False,
                disable_pump=False,
                reason=(
                    "At least one thermal module is above "
                    "the normal safe-temperature range."
                ),
            )

        # Everything is normal.
        return SafetyDecision(
            state=SystemState.SAFE,
            force_max_cooling=False,
            disable_heater=False,
            disable_pump=False,
            reason="All configured safety checks passed.",
        )


def apply_safety_override(
    command: ActuatorCommand,
    decision: SafetyDecision,
) -> ActuatorCommand:
    """
    Modify a controller command according to the safety decision.

    Safety has final authority.
    """

    if decision.disable_pump:
        command.pump_speed_pct = 0.0

    if (
        decision.force_max_cooling
        and not decision.disable_pump
    ):
        command.pump_speed_pct = 100.0
        command.fan_speed_pct = 100.0

    if decision.disable_heater:
        command.heater_enabled = False

    command.system_state = decision.state
    command.reason = decision.reason

    if decision.state in {
        SystemState.EMERGENCY,
        SystemState.FAULT,
    }:
        if decision.disable_pump:
            command.cooling_mode = CoolingMode.SHUTDOWN

    return command